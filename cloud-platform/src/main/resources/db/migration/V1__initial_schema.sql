CREATE TABLE IF NOT EXISTS chg_violation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    session_id VARCHAR(128),
    space_id VARCHAR(32) NOT NULL,
    plate VARCHAR(32),
    vehicle_type VARCHAR(32) NOT NULL,
    violation_type VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    evidence_url VARCHAR(512),
    event_status VARCHAR(24) NOT NULL DEFAULT 'ALARMING',
    cleared_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chg_events_space ON chg_violation_events(space_id);
CREATE INDEX IF NOT EXISTS idx_chg_events_plate ON chg_violation_events(plate);
CREATE INDEX IF NOT EXISTS idx_chg_events_occurred ON chg_violation_events(occurred_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_chg_events_session ON chg_violation_events(session_id) WHERE session_id IS NOT NULL AND session_id <> '';

CREATE TABLE IF NOT EXISTS chg_whitelist (
    plate VARCHAR(32) PRIMARY KEY,
    vehicle_type VARCHAR(32) DEFAULT 'ANY',
    reason VARCHAR(255),
    added_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    enabled BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS chg_node_heartbeats (
    node_id VARCHAR(64) PRIMARY KEY,
    last_heartbeat TIMESTAMPTZ NOT NULL,
    ip_address VARCHAR(64),
    status VARCHAR(16) DEFAULT 'ONLINE'
);

CREATE TABLE IF NOT EXISTS chg_platform_configuration (
    config_version BIGINT PRIMARY KEY,
    updated_at TIMESTAMPTZ NOT NULL,
    rules_json TEXT NOT NULL,
    bindings_json TEXT NOT NULL,
    whitelist_json TEXT NOT NULL DEFAULT '[]'
);

CREATE TABLE IF NOT EXISTS chg_operation_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(64) NOT NULL,
    action VARCHAR(128) NOT NULL,
    resource VARCHAR(128) NOT NULL,
    detail TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chg_audit_time ON chg_operation_audit(occurred_at);
