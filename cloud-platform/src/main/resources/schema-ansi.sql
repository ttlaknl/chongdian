-- ==========================================================
-- 充电车位防占位预警系统 ANSI SQL 通用数据库初始化脚本
-- 兼容矩阵: PostgreSQL 14+, 人大金仓 (KingbaseES V8/V9),
--           达梦数据库 (DM8), 华为 openGauss / GaussDB
-- ==========================================================

-- 1. 违规事件台账表
CREATE TABLE IF NOT EXISTS chg_violation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    space_id VARCHAR(32) NOT NULL,
    plate VARCHAR(32),
    vehicle_type VARCHAR(32) NOT NULL,
    violation_type VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    evidence_url VARCHAR(512),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chg_events_space ON chg_violation_events(space_id);
CREATE INDEX IF NOT EXISTS idx_chg_events_plate ON chg_violation_events(plate);
CREATE INDEX IF NOT EXISTS idx_chg_events_occurred ON chg_violation_events(occurred_at);

-- 2. 白名单车辆管理表
CREATE TABLE IF NOT EXISTS chg_whitelist (
    plate VARCHAR(32) PRIMARY KEY,
    vehicle_type VARCHAR(32) DEFAULT 'ANY',
    reason VARCHAR(255),
    added_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP,
    enabled SMALLINT DEFAULT 1
);

-- 3. 边缘节点心跳与在线监测表
CREATE TABLE IF NOT EXISTS chg_node_heartbeats (
    node_id VARCHAR(64) PRIMARY KEY,
    last_heartbeat TIMESTAMP NOT NULL,
    ip_address VARCHAR(64),
    status VARCHAR(16) DEFAULT 'ONLINE'
);

-- 4. 平台全局规则与配置版本表
CREATE TABLE IF NOT EXISTS chg_platform_configuration (
    config_version BIGINT PRIMARY KEY,
    updated_at TIMESTAMP NOT NULL,
    rules_json TEXT NOT NULL,
    bindings_json TEXT NOT NULL
);
