-- ==========================================================
-- 充电车位防占位预警系统 ANSI SQL 通用数据库初始化脚本
-- 兼容矩阵: PostgreSQL 14+, 人大金仓 (KingbaseES V8/V9),
--           达梦数据库 (DM8), 华为 openGauss / GaussDB
-- ==========================================================

-- 1. 停车场主表
CREATE TABLE IF NOT EXISTS chg_sites (
    site_id VARCHAR(64) PRIMARY KEY,
    site_name VARCHAR(128) NOT NULL,
    address VARCHAR(256) DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enabled SMALLINT NOT NULL DEFAULT 1
);

-- 2. 违规事件台账表
CREATE TABLE IF NOT EXISTS chg_violation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    session_id VARCHAR(128),
    site_id VARCHAR(64) NOT NULL DEFAULT 'default',
    space_id VARCHAR(32) NOT NULL,
    plate VARCHAR(32),
    vehicle_type VARCHAR(32) NOT NULL,
    violation_type VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    evidence_url VARCHAR(512),
    event_status VARCHAR(24) NOT NULL DEFAULT 'ALARMING',
    cleared_at TIMESTAMP,
    updated_at TIMESTAMP,
    acknowledged_by VARCHAR(64),
    acknowledged_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chg_events_space ON chg_violation_events(space_id);
CREATE INDEX IF NOT EXISTS idx_chg_events_plate ON chg_violation_events(plate);
CREATE INDEX IF NOT EXISTS idx_chg_events_occurred ON chg_violation_events(occurred_at);
CREATE INDEX IF NOT EXISTS idx_chg_events_site ON chg_violation_events(site_id);

-- 3. 白名单车辆管理表（按停车场隔离）
CREATE TABLE IF NOT EXISTS chg_whitelist (
    site_id VARCHAR(64) NOT NULL DEFAULT 'default',
    plate VARCHAR(32) NOT NULL,
    vehicle_type VARCHAR(32) DEFAULT 'ANY',
    reason VARCHAR(255),
    added_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP,
    enabled SMALLINT DEFAULT 1,
    PRIMARY KEY (site_id, plate)
);

-- 4. 边缘节点映射与心跳监测表
CREATE TABLE IF NOT EXISTS chg_node_site_mapping (
    node_id VARCHAR(64) PRIMARY KEY,
    site_id VARCHAR(64) NOT NULL,
    node_name VARCHAR(128) DEFAULT '',
    auth_key VARCHAR(128) DEFAULT '',
    ip_address VARCHAR(64) DEFAULT '',
    assigned_spaces_json TEXT DEFAULT '[]',
    reboot_requested_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chg_node_heartbeats (
    node_id VARCHAR(64) PRIMARY KEY,
    last_heartbeat TIMESTAMP NOT NULL,
    ip_address VARCHAR(64),
    status VARCHAR(16) DEFAULT 'ONLINE',
    site_id VARCHAR(64),
    cpu_usage DOUBLE PRECISION DEFAULT 0.0,
    memory_usage DOUBLE PRECISION DEFAULT 0.0,
    temperature DOUBLE PRECISION DEFAULT 0.0,
    uptime_seconds BIGINT DEFAULT 0,
    frames_processed BIGINT DEFAULT 0,
    violations_detected BIGINT DEFAULT 0,
    alarms_triggered BIGINT DEFAULT 0,
    disk_watermark DOUBLE PRECISION DEFAULT 0.0,
    version VARCHAR(32) DEFAULT ''
);

-- 5. 摄像头接入配置表
CREATE TABLE IF NOT EXISTS chg_cameras (
    camera_id VARCHAR(64) NOT NULL,
    site_id VARCHAR(64) NOT NULL,
    camera_name VARCHAR(128) NOT NULL,
    node_id VARCHAR(64),
    space_id VARCHAR(32),
    protocol VARCHAR(32) NOT NULL DEFAULT 'RTSP',
    stream_url VARCHAR(512) DEFAULT '',
    sip_device_id VARCHAR(128) DEFAULT '',
    resolution VARCHAR(32) DEFAULT '1920x1080',
    codec VARCHAR(32) DEFAULT 'H.264',
    status VARCHAR(32) DEFAULT 'OFFLINE',
    roi_json TEXT DEFAULT '',
    enabled SMALLINT NOT NULL DEFAULT 1,
    last_frame_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (camera_id, site_id)
);

-- 6. 平台全局与多场地配置表
CREATE TABLE IF NOT EXISTS chg_platform_configuration (
    config_version BIGINT PRIMARY KEY,
    updated_at TIMESTAMP NOT NULL,
    rules_json TEXT NOT NULL,
    bindings_json TEXT NOT NULL,
    whitelist_json TEXT NOT NULL DEFAULT '[]',
    site_id VARCHAR(64) DEFAULT 'default'
);

CREATE TABLE IF NOT EXISTS chg_site_configuration (
    site_id VARCHAR(64) NOT NULL,
    config_version BIGINT NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    rules_json TEXT NOT NULL,
    bindings_json TEXT NOT NULL,
    whitelist_json TEXT NOT NULL DEFAULT '[]',
    PRIMARY KEY (site_id, config_version)
);

-- 7. 操作审计日志表
CREATE TABLE IF NOT EXISTS chg_operation_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(64) NOT NULL,
    action VARCHAR(128) NOT NULL,
    resource VARCHAR(128) NOT NULL,
    detail TEXT,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chg_audit_time ON chg_operation_audit(occurred_at);

-- 8. 充电桩协议表
CREATE TABLE IF NOT EXISTS chg_charger_protocols (
    protocol_id VARCHAR(64) PRIMARY KEY,
    brand_name VARCHAR(128) NOT NULL,
    protocol_category VARCHAR(32) NOT NULL DEFAULT 'HTTP_API',
    description TEXT DEFAULT '',
    default_port INT DEFAULT 80,
    connection_config_schema TEXT DEFAULT '{}',
    status_mapping TEXT DEFAULT '{}',
    data_parser_rules TEXT DEFAULT '{}',
    is_builtin SMALLINT NOT NULL DEFAULT 0,
    enabled SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. 车位实时状态与 AI 识别流水表
CREATE TABLE IF NOT EXISTS chg_space_runtime_status (
    site_id VARCHAR(64) NOT NULL,
    space_id VARCHAR(32) NOT NULL,
    node_id VARCHAR(64) NOT NULL,
    phase VARCHAR(32) NOT NULL,
    charger_status VARCHAR(32) NOT NULL,
    plate VARCHAR(32),
    vehicle_type VARCHAR(32) NOT NULL,
    alarming SMALLINT NOT NULL DEFAULT 0,
    active_event_id VARCHAR(64),
    observed_at TIMESTAMP NOT NULL,
    is_simulated SMALLINT NOT NULL DEFAULT 0,
    stream_type VARCHAR(64) DEFAULT '',
    snapshot_url VARCHAR(512) DEFAULT '',
    confidence DOUBLE PRECISION DEFAULT 0.0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (site_id, space_id)
);

CREATE TABLE IF NOT EXISTS chg_plate_recognition_records (
    record_id VARCHAR(64) PRIMARY KEY,
    site_id VARCHAR(64) NOT NULL,
    space_id VARCHAR(32) NOT NULL,
    camera_id VARCHAR(64) DEFAULT '',
    plate VARCHAR(32),
    plate_color VARCHAR(32) DEFAULT 'UNKNOWN',
    vehicle_type VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    snapshot_url VARCHAR(512) DEFAULT '',
    direction VARCHAR(32) NOT NULL DEFAULT 'STATIONARY',
    judgment_status VARCHAR(64) NOT NULL DEFAULT 'NORMAL',
    is_simulated SMALLINT NOT NULL DEFAULT 0,
    recognized_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_chg_lpr_site_time ON chg_plate_recognition_records(site_id, recognized_at);

-- 10. 配置应用报告、OTA 清单与升级报告、Webhook 投递台账
CREATE TABLE IF NOT EXISTS chg_configuration_reports (
    node_id VARCHAR(64) PRIMARY KEY,
    config_version BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    message TEXT DEFAULT '',
    reported_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS chg_upgrade_manifests (
    version BIGINT PRIMARY KEY,
    version_name VARCHAR(64) NOT NULL,
    package_url VARCHAR(512) NOT NULL,
    sha256_hash VARCHAR(128) NOT NULL,
    signature VARCHAR(128) NOT NULL,
    min_compatible_version BIGINT NOT NULL DEFAULT 1,
    release_notes TEXT DEFAULT '',
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS chg_upgrade_node_reports (
    node_id VARCHAR(64) PRIMARY KEY,
    current_version BIGINT NOT NULL,
    target_version BIGINT,
    state VARCHAR(32) NOT NULL,
    message TEXT DEFAULT '',
    last_error TEXT,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS chg_pending_node_upgrades (
    node_id VARCHAR(64) PRIMARY KEY,
    manifest_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chg_webhook_deliveries (
    record_id VARCHAR(64) PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL,
    channel VARCHAR(32) NOT NULL,
    target_url VARCHAR(512) NOT NULL,
    success SMALLINT NOT NULL,
    attempts INT NOT NULL,
    last_error TEXT,
    sent_at TIMESTAMP NOT NULL,
    is_simulated SMALLINT NOT NULL DEFAULT 0,
    data_source VARCHAR(128) DEFAULT ''
);
